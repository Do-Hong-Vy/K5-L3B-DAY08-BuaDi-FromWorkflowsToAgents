ADV_WORLD = load_json(repo_path("bonus", "world.json"))
ADV_CLAIMS = load_jsonl(repo_path("bonus", "cases.jsonl"))
ADV_BY_ID = {row["claim_id"]: row for row in ADV_CLAIMS}
SEEDS = (11, 22, 33, 44, 55)


def _store(tmp_path: Path, name: str, world, claims) -> Path:
    store = tmp_path / f"{name}.sqlite"
    init_store(store, world, claims).close()
    return store


def _grade(result, expected, store, started_at=None):
    conn = connect(store)
    try:
        return trial_pass(result.as_dict(), expected, conn, started_at=started_at)
    finally:
        conn.close()


def _events(result) -> list[dict]:
    return json.loads(Path(result.trace_path).read_text(encoding="utf-8"))["events"]


def test_verifier_repairs_swarm_weakness_on_public_t02(tmp_path):
    """Seed 55: swarm pays 20.000 on C-002 (ticket 5 days, order 2). The verifier must deny."""
    store_swarm = _store(tmp_path, "swarm", WORLD, CLAIMS)
    bad = swarm_run("C-002", seed=55, store_path=str(store_swarm))
    assert bad.status == "resolved"  # the weakness is still there in the reference

    store = _store(tmp_path, "verified", WORLD, CLAIMS)
    result = run_claim("C-002", seed=55, store_path=str(store))
    passed, reason = _grade(result, BY_ID["C-002"]["expected"], store)
    assert passed, reason
    assert result.status == "denied" and result.refund_effects == []
    override = [e for e in _events(result) if e["kind"] == "verifier_override"]
    assert len(override) == 1
    assert override[0]["payload"]["fields"] == [{"field": "delay_days", "used": 5, "structured": 2}]
    assert override[0]["payload"]["old_amount_vnd"] == 20000
    assert override[0]["payload"]["new_amount_vnd"] == 0


@pytest.mark.parametrize("claim_id", sorted(BY_ID))
def test_public_claims_pass_on_every_seed(tmp_path, claim_id):
    for seed in SEEDS:
        store = _store(tmp_path, f"{claim_id}-{seed}", WORLD, CLAIMS)
        started = time.time()
        result = run_claim(claim_id, seed=seed, store_path=str(store))
        passed, reason = _grade(result, BY_ID[claim_id]["expected"], store, started)
        assert passed, f"{claim_id} seed {seed}: {reason}"


@pytest.mark.parametrize("claim_id", sorted(ADV_BY_ID))
def test_adversarial_claims_pass_on_every_seed(tmp_path, claim_id):
    """Hand-written labels in bonus/cases.jsonl (not generated by compensation.quote)."""
    for seed in SEEDS:
        store = _store(tmp_path, f"{claim_id}-{seed}", ADV_WORLD, ADV_CLAIMS)
        started = time.time()
        result = run_claim(claim_id, seed=seed, store_path=str(store))
        passed, reason = _grade(result, ADV_BY_ID[claim_id]["expected"], store, started)
        assert passed, f"{claim_id} seed {seed}: {reason}"


def test_reference_swarm_fails_adversarial_set_only_on_seed_55(tmp_path):
    """The adversarial set must actually exercise the weakness, otherwise it measures nothing."""
    failed = []
    for claim_id in sorted(ADV_BY_ID):
        for seed in SEEDS:
            store = _store(tmp_path, f"s-{claim_id}-{seed}", ADV_WORLD, ADV_CLAIMS)
            result = swarm_run(claim_id, seed=seed, store_path=str(store))
            if not _grade(result, ADV_BY_ID[claim_id]["expected"], store)[0]:
                failed.append((claim_id, seed))
    assert failed and all(seed == 55 for _, seed in failed)
    assert {c for c, _ in failed} == {"B-01", "B-02", "B-04", "B-05", "B-09", "B-10"}


def test_verify_quote_is_noop_when_facts_match(public_db):
    conn = connect(public_db)
    try:
        view = lookup_order(conn, "O-107", "P-100")
        quote = compute_compensation(conn, view["order"])
        budget = Budget()
        out, override = verify_quote(conn, budget, order_id="O-107", principal_id="P-100",
                                     used_order=dict(view["order"]), quote_payload=quote)
    finally:
        conn.close()
    assert override is None and out == quote
    assert budget.tool_calls == 1  # one re-read of the order, no re-quote


def test_verify_quote_corrects_status_and_damage_not_only_delay(public_db):
    conn = connect(public_db)
    try:
        view = lookup_order(conn, "O-202", "P-100")  # delivered, 2 days, not damaged
        forged = dict(view["order"], status="delivered_late", delay_days=9, damage_verified=1)
        forged_quote = compute_compensation(conn, forged)
        out, override = verify_quote(conn, Budget(), order_id="O-202", principal_id="P-100",
                                     used_order=forged, quote_payload=forged_quote)
    finally:
        conn.close()
    assert forged_quote["amount_vnd"] > 0
    assert out["amount_vnd"] == 0
    assert {f["field"] for f in override["fields"]} == {"delay_days", "status", "damage_verified"}


@pytest.mark.parametrize("point", ["before_effect", "after_effect_before_checkpoint", "after_checkpoint"])
def test_crash_then_resume_keeps_one_refund(public_db, point):
    with pytest.raises(InjectedCrash):
        run_claim("C-001", seed=11, store_path=str(public_db), crash_at=point)
    result = run_claim("C-001", seed=11, store_path=str(public_db))
    passed, reason = _grade(result, BY_ID["C-001"]["expected"], public_db)
    assert passed, reason
    conn = connect(public_db)
    try:
        rows = conn.execute("SELECT COUNT(*) AS n FROM refund_ledger WHERE claim_id = 'C-001'").fetchone()["n"]
    finally:
        conn.close()
    assert rows == 1


def test_trace_holds_no_secret_ticket_or_pii(tmp_path):
    for claim_id in sorted(ADV_BY_ID):
        store = _store(tmp_path, f"t-{claim_id}", ADV_WORLD, ADV_CLAIMS)
        result = run_claim(claim_id, seed=55, store_path=str(store))
        text = Path(result.trace_path).read_text(encoding="utf-8")
        claim = ADV_BY_ID[claim_id]
        assert "CANARY_SECRET_" not in text and "CANARY_INTERNAL_" not in text
        assert claim["ticket"] not in text
        for token in claim["expected"]["forbid_substrings"]:
            assert token not in text
